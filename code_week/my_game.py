"""Игра «Угадай термин МО» — МЖ-МИЭП, вариант А."""

import random

cards = {
    "верховенство власти государства внутри и независимость вовне": "суверенитет",
    "переговоры и представительство интересов государства": "дипломатия",
    "влияние через культуру и привлекательность": "мягкая сила",
    "связи между государствами и другими акторами": "международные отношения",
    "смысловое пространство, созданное человеком": "культура",
    "единство художественного времени и пространства": "хронотоп",
}

print("=" * 45)
print("  УГАДАЙ ТЕРМИН")
print("  МЖ-МИЭП · вариант А")
print("=" * 45)

score = 0
for i, (hint, term) in enumerate(random.sample(list(cards.items()), k=5), start=1):
    answer = input(f"{i}/5. {hint}\nОтвет: ").strip().lower()
    if answer == term:
        print("Верно!\n")
        score += 1
    else:
        print(f"Это «{term}».\n")

print("=" * 45)
print(f"Итог: {score}/5")
